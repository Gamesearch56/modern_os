import json, sys
path, dest = sys.argv[1], sys.argv[2]
data = json.load(open(path))
c = data.get("color") or {}
def hx(key, fallback):
    v = str(c.get(key) or fallback)
    if not v.startswith("#"):
        v = "#" + v
    return v
primary = hx("primary", "#6750A4")
