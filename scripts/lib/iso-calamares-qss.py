# Commons/Tokens.qml interaction.hover / .press. QSS has no overlay, so
# the MD3 state layer (the ink color over the container) is pre-mixed.
HOVER, PRESS = 0.08, 0.12


def mix(base, ink, t):
    b = [int(base[i:i + 2], 16) for i in (1, 3, 5)]
    k = [int(ink[i:i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{round(x + (y - x) * t):02x}" for x, y in zip(b, k))


def states(selector, base, ink):
    parts = [s.strip() for s in selector.split(",")]
    hover = ", ".join(f"{s}:enabled:hover" for s in parts)
    press = ", ".join(f"{s}:enabled:pressed" for s in parts)
    return (f"{hover} {{\n    background-color: {mix(base, ink, HOVER)};\n    color: {ink};\n}}\n"
            f"{press} {{\n    background-color: {mix(base, ink, PRESS)};\n    color: {ink};\n}}\n")


