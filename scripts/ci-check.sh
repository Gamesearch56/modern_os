mapfile -t files < <(git ls-files '*.sh' | grep -E '^(install/|scripts/|tests/|iso/airootfs/)')
[ ${#files[@]} -gt 0 ] || die "no shell scripts matched CI's git ls-files filter"
shellcheck "${files[@]}"
