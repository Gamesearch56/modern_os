#!/usr/bin/env bash
# Rewrites the Plymouth splash script from the live tokens.json.
# Staged only: writes under $XDG_STATE_HOME/modern/plymouth/ (or --dest).
# NEVER runs mkinitcpio or plymouth-set-default-theme — those rewrite the
# initramfs and are a gated operator step (docs/ISOLATION.md, docs/DECISIONS.md #13).
#
# Usage: plymouth-sync.sh [--dest DIR]
set -euo pipefail

log()  { printf '[plymouth-sync] %s\n' "$*"; }
die()  { printf '[plymouth-sync] ERROR %s\n' "$*" >&2; exit 1; }

TOKENS="$HOME/.config/modern/tokens.json"
DEST="${XDG_STATE_HOME:-$HOME/.local/state}/modern/plymouth"

while [ $# -gt 0 ]; do
    case "$1" in
        --dest)
            [ $# -ge 2 ] || die "--dest needs a value"
            DEST="$2"; shift 2 ;;
        -h|--help)
            grep '^#' "$0" | cut -c3- | head -n12
            exit 0 ;;
        *) die "unknown argument: $1" ;;
    esac
done

command -v jq >/dev/null 2>&1 || die "jq not on PATH"
[ -f "$TOKENS" ] || die "missing $TOKENS — run theme-apply.sh first"

hex_to_frac() {
    local hex="${1#\#}"
    hex="${hex^^}"
    local r g b
    r=$((16#${hex:0:2}))
    g=$((16#${hex:2:2}))
    b=$((16#${hex:4:2}))
    awk -v r="$r" -v g="$g" -v b="$b" 'BEGIN { printf "%.4f, %.4f, %.4f", r/255, g/255, b/255 }'
}

SURFACE="$(jq -r '.color.surface // "#141218"' "$TOKENS")"
PRIMARY="$(jq -r '.color.primary // "#D0BCFF"' "$TOKENS")"
SURFACE_RGB="$(hex_to_frac "$SURFACE")"
PRIMARY_RGB="$(hex_to_frac "$PRIMARY")"

mkdir -p "$DEST"

cat > "$DEST/modern.plymouth" <<'EOF'
[Plymouth Theme]
Name=modern
Description=Material Design 3 boot splash for modern_dotfile
ModuleName=script

[script]
ImageDir=/usr/share/plymouth/themes/modern
ScriptFile=/usr/share/plymouth/themes/modern/modern.script
EOF

cat > "$DEST/modern.script" <<EOF
# Generated by plymouth-sync.sh from tokens.json — do not hand-edit.
# Preview only. The installed splash stays the staged installer colors.
Window.SetBackgroundTopColor(${SURFACE_RGB});
Window.SetBackgroundBottomColor(${SURFACE_RGB});

title.image = Image.Text("ModernOS", ${PRIMARY_RGB}, 1.0, "Sans 120", "center");
title.sprite = Sprite(title.image);

spin_count = 12;
spin_radius = 42;
spin_gap = 56;
spin_phase = 0;
for (i = 0; i < spin_count; i++)
  {
    dots[i].image = Image.Text("●", ${PRIMARY_RGB}, 1.0, "Sans 22", "center");
    dots[i].sprite = Sprite(dots[i].image);
  }

fun refresh_callback()
  {
    spin_phase = spin_phase + 0.09;
    cx = Window.GetX() + Window.GetWidth() / 2;
    top = Window.GetY() + Window.GetHeight() / 2 - (title.image.GetHeight() + spin_gap + spin_radius * 2) / 2;
    title.sprite.SetX(cx - title.image.GetWidth() / 2);
    title.sprite.SetY(top);
    sy = top + title.image.GetHeight() + spin_gap + spin_radius;
    for (i = 0; i < spin_count; i++)
      {
        ang = spin_phase + i * (2 * Math.Pi / spin_count);
        dots[i].sprite.SetX(cx + Math.Cos(ang) * spin_radius - dots[i].image.GetWidth() / 2);
        dots[i].sprite.SetY(sy + Math.Sin(ang) * spin_radius - dots[i].image.GetHeight() / 2);
        dots[i].sprite.SetOpacity(0.2 + 0.8 * i / (spin_count - 1));
      }
  }

Plymouth.SetRefreshFunction(refresh_callback);
EOF

log "wrote $DEST/modern.script (surface=$SURFACE primary=$PRIMARY)"
log "not installing: copy to /usr/share/plymouth/themes/modern/ and run mkinitcpio yourself"
